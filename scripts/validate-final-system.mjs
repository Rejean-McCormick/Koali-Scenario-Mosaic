import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const manifest=JSON.parse(readFileSync(resolve(root,'src/data/public-architecture.v1.json'),'utf8'));
assert.equal(manifest.format,'koa.public-architecture.v1');
assert.equal(manifest.classification,'PUBLIC_DESIGN_METADATA_ONLY');
assert.equal(manifest.status,'TARGET_DESIGN_NOT_DEPLOYMENT_EVIDENCE');
assert.equal(manifest.chains.length,24);
assert.equal(manifest.repositories.length,53);
assert.equal(manifest.boundaries.length,26);
assert.equal(new Set(manifest.chains.map(c=>c.id)).size,24);
assert.equal(new Set(manifest.boundaries.map(b=>b.id)).size,26);
for(const c of manifest.chains)assert.equal(c.state,'target_design_not_qualified');
for(const b of manifest.boundaries)assert.equal(b.state,'target_design_not_qualified');
const raw=JSON.stringify(manifest);
for(const key of ['local_root','source_member','snapshot_member','password','git_revision'])assert.equal(raw.includes('"'+key+'"'),false);
assert.equal(raw.includes('C:\\mycode\\'),false);
console.log('PASS: 24 target chains, 53 owners, 26 design-only boundaries; safe public metadata');
